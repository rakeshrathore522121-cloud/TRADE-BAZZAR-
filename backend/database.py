IntegrityError = sqlite3.IntegrityError


class CompatRow(dict):
    """dict-like row that also supports row[0] style access."""
    def __init__(self, keys, values):
        super().__init__(zip(keys, values))
        self._keys = list(keys)

    def __getitem__(self, key):
        if isinstance(key, int):
            return super().__getitem__(self._keys[key])
        return super().__getitem__(key)


class PGCursor:
    def __init__(self, cursor):
        self._cursor = cursor
        self._prefetched = None
        self._lastrowid = None

    @property
    def lastrowid(self):
        return self._lastrowid

    def _row(self, raw):
        if raw is None:
            return None
        keys = [d[0] for d in self._cursor.description]
        return CompatRow(keys, raw)

    def fetchone(self):
        if self._prefetched is not None:
            raw = self._prefetched
            self._prefetched = None
            return self._row(raw)
        return self._row(self._cursor.fetchone())

    def fetchall(self):
        rows = []
        if self._prefetched is not None:
            rows.append(self._row(self._prefetched))
            self._prefetched = None
        rows.extend(self._row(r) for r in self._cursor.fetchall())
        return rows

    def __iter__(self):
        return iter(self.fetchall())


class PGConnection:
    def __init__(self, conn):
        self._conn = conn

    def _convert_sql(self, sql):
        sql = sql.replace("INSERT OR IGNORE INTO", "INSERT INTO")
        # Existing application SQL uses SQLite's ? placeholders.
        sql = sql.replace("?", "%s")
        # INSERT OR IGNORE is handled by database initialization separately;
        # this also protects any future use in the app.
        if "ON CONFLICT" not in sql and sql.lstrip().upper().startswith("INSERT INTO"):
            table_match = re.search(r"INSERT\s+INTO\s+([A-Za-z_][A-Za-z0-9_]*)", sql, re.I)
            table = table_match.group(1).lower() if table_match else ""
            if table not in {"settings"} and "RETURNING" not in sql.upper():
                sql += " RETURNING id"
        return sql

    def execute(self, sql, params=()):
        converted = self._convert_sql(sql)
        cur = self._conn.cursor()
        try:
            cur.execute(converted, params or ())
        except Exception as exc:
            # Preserve the existing app.py IntegrityError handling.
            if exc.__class__.__name__ in {"UniqueViolation", "ForeignKeyViolation", "NotNullViolation", "CheckViolation"}:
                raise IntegrityError(str(exc)) from exc
            raise
        out = PGCursor(cur)
        if "RETURNING id" in converted.upper():
            raw = cur.fetchone()
            out._prefetched = raw
            if raw is not None:
                out._lastrowid = raw[0]
        return out

    def executescript(self, script):
        # Used only by the legacy SQLite path. Kept for API compatibility.
        cur = self._conn.cursor()
        cur.execute(script)
        return PGCursor(cur)

    def commit(self):
        self._conn.commit()

    def rollback(self):
        self._conn.rollback()

    def close(self):
        self._conn.close()


