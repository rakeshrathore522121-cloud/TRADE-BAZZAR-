def get_connection():
    if not USE_POSTGRES:
        conn = sqlite3.connect(DB_PATH)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA foreign_keys = ON")
        return conn

    import psycopg2
    raw = psycopg2.connect(DATABASE_URL, connect_timeout=15)
    return PGConnection(raw)


